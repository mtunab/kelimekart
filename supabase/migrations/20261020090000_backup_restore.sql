-- Aşama 7: yedekten geri yükleme desteği.
-- Geri yüklenen tekrar kayıtları eski numaralarını (id) koruyabilsin diye kimlik sütunu
-- "always" yerine "by default" olur. Normal kullanımda değişen bir şey yok: numarayı yine
-- veritabanı verir; istemcinin bu tabloya doğrudan yazma izni zaten yok.
alter table public.review_logs alter column id set generated by default;

-- Geri yüklemeden sonra numara sayacını en büyük numaranın ilerisine taşır
-- (yeni kayıtlar geri yüklenenlerle çakışmasın). Sadece sunucu betikleri (service_role) çağırabilir.
create or replace function public.sync_review_logs_sequence()
returns bigint
language sql
security definer
set search_path = ''
as $$
  select setval(
    pg_get_serial_sequence('public.review_logs', 'id'),
    greatest((select coalesce(max(id), 0) from public.review_logs), 1)
  )
$$;

revoke execute on function public.sync_review_logs_sequence() from public, anon, authenticated;
grant execute on function public.sync_review_logs_sequence() to service_role;
